  const keys = Object.keys(dictionary).sort((a,b)=>b.length-a.length);
  function translateText(value) {
    let out = String(value);
    for (const key of keys) {
      if (out === key) return dictionary[key];
    }
    for (const key of keys) out = out.split(key).join(dictionary[key]);
    return out;
  }
  function apply(root) {
    if (!root || localStorage.getItem("ttk-language") !== "bn") return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);
    for (const node of nodes) {
      if (node.parentElement?.closest("script,style,textarea,code,[data-no-translate]")) continue;
      node.nodeValue = translateText(node.nodeValue);
    }
    root.querySelectorAll("input[placeholder],textarea[placeholder],button[aria-label],img[alt],a[title],button[title],select[aria-label]").forEach(el => {
      for (const attr of ["placeholder","aria-label","alt","title"]) {
        if (el.hasAttribute(attr)) el.setAttribute(attr, translateText(el.getAttribute(attr)));
      }
    });
    root.querySelectorAll("option").forEach(el => { el.textContent = translateText(el.textContent); });
    root.setAttribute("lang","bn");
  }
